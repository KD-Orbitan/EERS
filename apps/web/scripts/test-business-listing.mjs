const Module = require('node:module');
const originalLoad = Module._load;
const uploads = [];
let failCover = true;
const api = { post: async (url, data) => { uploads.push({ url, fields: [...data.keys()] }); if (failCover && url.endsWith('/cover')) throw new Error('Network error'); } };
Module._load = function(id, ...args) {
  if (id === '@/lib/api-client') return { __esModule: true, default: api };
  if (id === '@/lib/business-profile-fields') return profile;
  if (id === '@/lib/image-upload') return require('../app/lib/image-upload.ts');
  return originalLoad.call(this, id, ...args);
};
